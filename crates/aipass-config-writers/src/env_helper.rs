//! Launch helpers use the host shell, never persistent user/system environment.
use crate::ToolEntry;
use std::path::{Path, PathBuf};

pub fn helper_path(home: &Path, tool: &str) -> PathBuf {
    home.join(".aipass/tools").join(format!(
        "{tool}.{}",
        if cfg!(windows) { "ps1" } else { "env" }
    ))
}

pub fn shell_quote(value: &str) -> String {
    quote(value, cfg!(windows))
}
fn quote(value: &str, windows: bool) -> String {
    format!(
        "'{}'",
        if windows {
            value.replace('\'', "''")
        } else {
            value.replace('\'', "'\\''")
        }
    )
}

pub fn env_literal(name: &str, value: &str) -> String {
    assignment(name, &shell_quote(value), cfg!(windows))
}
fn assignment(name: &str, value: &str, windows: bool) -> String {
    assert!(name.chars().all(|c| c.is_ascii_alphanumeric() || c == '_'));
    if windows {
        format!("$env:{name} = {value}\r\n")
    } else {
        format!("export {name}={value}\n")
    }
}

pub fn env_credential(entry: &ToolEntry, name: &str) -> String {
    env_credential_for(entry, name, cfg!(windows))
}
fn env_credential_for(entry: &ToolEntry, name: &str, windows: bool) -> String {
    let command = entry.credential_command_for(windows);
    if windows {
        // Clear stale credentials first and never retain a previous key after
        // the vault/helper fails. No execution-policy bypass or persistent env.
        format!("Remove-Item Env:{name} -ErrorAction SilentlyContinue\r\n$aipassValue = & {command}\r\nif ($LASTEXITCODE -ne 0 -or [string]::IsNullOrWhiteSpace([string]$aipassValue)) {{ throw 'AIPass credential lookup failed' }}\r\n$env:{name} = [string]$aipassValue\r\nRemove-Variable aipassValue\r\n")
    } else {
        format!("unset {name}\n{name}=\"$({command})\" || return $?\n[ -n \"${{{name}}}\" ] || return 1\nexport {name}\n")
    }
}

pub fn shell_env(entry: &ToolEntry, name: &str, key: Option<&str>) -> String {
    let mut out = if cfg!(windows) {
        String::from("\u{feff}")
    } else {
        String::new()
    };
    out.push_str("# Generated by AIPass. Load in the shell that starts the Agent.\n");
    out.push_str(
        &key.map(|key| env_literal(name, key))
            .unwrap_or_else(|| env_credential(entry, name)),
    );
    out
}

#[cfg(test)]
mod tests {
    use super::*;
    #[test]
    fn shell_literals_cover_metacharacters_and_windows_paths() {
        let value = r"C:\Users\中文 O'Brien\$(untrusted)`;&%PATH%!";
        assert_eq!(
            quote(value, true),
            format!("'{}'", value.replace('\'', "''"))
        );
        assert_eq!(
            quote(value, false),
            format!("'{}'", value.replace('\'', "'\\''"))
        );
        assert!(assignment("KEY", &quote(value, true), true).starts_with("$env:KEY = '"));
    }
    #[test]
    fn powershell_runs_literal_and_credential_helpers_without_interpolation() {
        use aipass_provider_registry::{AuthScheme, InterfaceType};
        let shell = if cfg!(windows) {
            "powershell.exe"
        } else {
            "pwsh"
        };
        if std::process::Command::new(shell)
            .arg("-Version")
            .output()
            .is_err()
        {
            if cfg!(windows) {
                panic!("Windows PowerShell is required");
            }
            return;
        }
        let dir = tempfile::tempdir().unwrap();
        let entry = ToolEntry {
            supports_websockets: None,
            id: uuid::Uuid::new_v4(),
            secret_id: Some("selected O'Brien & $(throw) 中文".into()),
            title: "fixture".into(),
            provider_id: None,
            endpoint: None,
            interface_type: InterfaceType::OpenAiCompatible,
            auth_scheme: AuthScheme::Bearer,
            env_key: "FIXTURE_API_KEY".into(),
            default_model: None,
            api_key: None,
        };
        let secret = entry.secret_id.as_deref().unwrap();
        let stub = format!("\u{feff}if ($args[0] -ne 'get' -or $args[2] -ne '--secret-id' -or $args[3] -ne {}) {{ exit 71 }}; [Console]::Write('fixture-key'); exit 0", quote(secret, true));
        std::fs::write(dir.path().join("aipass.ps1"), stub).unwrap();
        let mut setup = format!("$ErrorActionPreference = 'Stop'\n$env:PATH = {} + [IO.Path]::PathSeparator + $env:PATH\n", quote(&dir.path().to_string_lossy(), true));
        if !cfg!(windows) {
            setup.push_str("function powershell.exe { & pwsh @args }\n");
        }
        let literal = "prefix O'Brien 中文 `$() & %PATH%!";
        let script = format!("\u{feff}{setup}{}{}[Console]::OutputEncoding = [Text.UTF8Encoding]::new($false)\n[Console]::Write($env:FIXTURE_LITERAL + '|' + $env:FIXTURE_API_KEY)\nexit 0", assignment("FIXTURE_LITERAL", &quote(literal, true), true), env_credential_for(&entry, "FIXTURE_API_KEY", true));
        let file = dir.path().join("check.ps1");
        std::fs::write(&file, script).unwrap();
        let out = std::process::Command::new(shell)
            .args(["-NoProfile", "-NonInteractive", "-File"])
            .arg(&file)
            .output()
            .unwrap();
        assert!(
            out.status.success(),
            "{}",
            String::from_utf8_lossy(&out.stderr)
        );
        assert_eq!(
            String::from_utf8(out.stdout).unwrap(),
            format!("{literal}|fixture-key")
        );
        std::fs::write(dir.path().join("aipass.ps1"), "exit 73").unwrap();
        let script = format!("\u{feff}{setup}$env:FIXTURE_API_KEY = 'stale'\ntry {{ {} throw 'unexpected success' }} catch {{ if (Test-Path Env:FIXTURE_API_KEY) {{ exit 91 }} }}; exit 0", env_credential_for(&entry, "FIXTURE_API_KEY", true));
        std::fs::write(&file, script).unwrap();
        assert!(std::process::Command::new(shell)
            .args(["-NoProfile", "-NonInteractive", "-File"])
            .arg(file)
            .output()
            .unwrap()
            .status
            .success());
    }
}
